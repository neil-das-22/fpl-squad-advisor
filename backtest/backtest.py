# 7. RECOMMENDATIONS — data-driven, named against real xp_model constants
# ---------------------------------------------------------------------------

@dataclass
class Recommendation:
    constant: str
    direction: str          # "increase" | "decrease" | "investigate"
    evidence: str
    confidence: str         # "high" | "medium" | "low"


def _fmt(x: float, nd: int = 3) -> str:
    return "n/a" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{nd}f}"


def never_appeared_analysis(full_results: pd.DataFrame) -> dict[str, float]:
    """Quantify the model's treatment of players with zero prior minutes.

    Isolated as its own function because it turned out to be the single largest
    error source in the whole backtest, and because the finding is a LOGIC bug
    rather than a mis-set constant — it deserves to be measurable on its own.

    A player who has recorded 0 minutes across N completed gameweeks is one of
    the most confidently-predictable players in the pool: he is not going to
    play. `estimate_start_probability()` instead routes him down the same branch
    as a genuine GW1 cold start (`minutes <= 0`) and hands him the flat
    DEFAULT_START_PROBABILITY.
    """
    df = full_results[full_results["n_gws_available"] >= COLD_START_MAX_GW]
    if len(df) == 0:
        return {"n": 0}
    ghost = df[df["n_appearances"].fillna(0) == 0]
    if len(ghost) == 0:
        return {"n": 0}
    return {
        "n": int(len(ghost)),
        "share_of_pool": float(len(ghost) / len(df)),
        "mean_pred": float(ghost["predicted"].mean()),
        "mean_actual": float(ghost["actual"].mean()),
        "mean_p_start": float(ghost["p_start"].mean()),
        "pct_who_played": float((ghost["minutes"].astype(float) > 0).mean()),
        "signed_error": float((ghost["predicted"] - ghost["actual"]).sum()),
        "pool_signed_error": float((df["predicted"] - df["actual"]).sum()),
    }


def derive_recommendations(results: pd.DataFrame,
                           components: pd.DataFrame,
                           full_results: pd.DataFrame | None = None,
                           defcon: dict[str, Any] | None = None,
                           ) -> list[Recommendation]:
    """Turn component-level bias into concrete, named constant recommendations.

    Every threshold below is a judgement call about what counts as "material" at
    the scale of one player-gameweek (where the whole distribution has a mean
    around 2 points). They are deliberately conservative: this pass should
    surface a short list of real problems, not 30 marginal ones.

    Args:
        results: the CREDIBLE pool (players with >= 1 prior appearance).
            Component biases are read from here because the full pool is
            dominated by never-appeared squad filler, whose error swamps every
            component signal and would produce confidently wrong advice
            ("lower BONUS_SCALE") about constants that are in fact fine.
        components: `component_comparison(results)` on that same slice.
        full_results: the whole pool, used only for the never-appeared finding.
        defcon: output of `defcon_experiment()`, for the data-gap finding.
    """
    recs: list[Recommendation] = []
    comp = components.set_index("component")

    # --- the big one: zero-prior-minutes players --------------------------
    ghost = never_appeared_analysis(full_results if full_results is not None else results)
    if ghost.get("n", 0) > 100:
        share = (ghost["signed_error"] / ghost["pool_signed_error"] * 100.0
                 if ghost["pool_signed_error"] else float("nan"))
        recs.append(Recommendation(
            "estimate_start_probability() `minutes <= 0` guard "
            "(+ DEFAULT_START_PROBABILITY)",
            "fix logic, not the constant",
            f"**This is the largest single error source in the backtest and it "
            f"is a logic bug, not a mis-tuned number.**\n\n"
            f"`estimate_start_probability()` branches on\n\n"
            f"    if matches_played is None or matches_played < 1 or minutes <= 0:\n"
            f"        base = default_start_probability   # {m.DEFAULT_START_PROBABILITY}\n\n"
            f"That `minutes <= 0` clause conflates two opposite situations: "
            f"\"it is GW1 and nobody has played yet\" (no information) and "
            f"\"this player has logged zero minutes across every completed "
            f"gameweek so far\" (extremely strong information). The second group "
            f"gets handed a {m.DEFAULT_START_PROBABILITY:.0%} start probability.\n\n"
            f"Measured over gameweeks {COLD_START_MAX_GW + 1}-38: "
            f"{ghost['n']:,} player-gameweeks ({ghost['share_of_pool']:.1%} of "
            f"the pool) had zero prior appearances. The model gave them a mean "
            f"p_start of {_fmt(ghost['mean_p_start'], 3)} and predicted "
            f"{_fmt(ghost['mean_pred'], 2)} xP each. They actually scored "
            f"{_fmt(ghost['mean_actual'], 3)} points on average and featured at "
            f"all in {ghost['pct_who_played']:.1%} of cases.\n\n"
            f"Those rows alone account for {_fmt(ghost['signed_error'], 0)} "
            f"points of signed error against a whole-pool total of "
            f"{_fmt(ghost['pool_signed_error'], 0)} — i.e. {_fmt(share, 0)}% of "
            f"all the model's over-prediction. Excluding them the model actually "
            f"*under*-predicts slightly, and its rank correlation roughly "
            f"triples.\n\n"
            f"Suggested fix (for human review): make the fallback conditional on "
            f"season progress rather than on minutes being zero — e.g. if "
            f"`matches_played >= 3` and `minutes == 0`, the empirical start rate "
            f"is ~1%, so return something near MIN_START_PROBABILITY "
            f"({m.MIN_START_PROBABILITY}) instead of DEFAULT_START_PROBABILITY. "
            f"Reserve the flat prior for the genuine no-data case "
            f"(`matches_played < 1`). Do NOT simply lower "
            f"DEFAULT_START_PROBABILITY: that would wrongly punish real GW1 "
            f"starters, who are the case it exists to serve.",
            "high"))

    def cbias(name: str) -> float:
        return float(comp.loc[name, "bias"]) if name in comp.index else float("nan")

    def cpred(name: str) -> float:
        return float(comp.loc[name, "mean_pred"]) if name in comp.index else float("nan")

    def cact(name: str) -> float:
        return float(comp.loc[name, "mean_actual"]) if name in comp.index else float("nan")

    # --- overall level ----------------------------------------------------
    overall_bias = bias(results["predicted"], results["actual"])
    if abs(overall_bias) > 0.25:
        recs.append(Recommendation(
            "OVERALL LEVEL (no single constant)",
            "decrease" if overall_bias > 0 else "increase",
            f"Model {'over' if overall_bias > 0 else 'under'}-predicts by "
            f"{_fmt(abs(overall_bias), 2)} pts per player-gameweek on average "
            f"(mean predicted {_fmt(results['predicted'].mean(), 2)} vs mean "
            f"actual {_fmt(results['actual'].mean(), 2)}). Read the "
            f"component table below before touching anything global — the level "
            f"error is almost always concentrated in one or two components. "
            f"NOTE: some over-prediction is expected and NOT a model fault, "
            f"because the backtest cannot see per-gameweek injury status "
            f"(LIMITATION #2) and so predicts points for players who were out.",
            "high"))

    # --- appearance / minutes --------------------------------------------
    app_bias = cbias("appearance")
    if abs(app_bias) > 0.15:
        recs.append(Recommendation(
            "DEFAULT_START_PROBABILITY / SUB_APPEARANCE_RATE / P_60_GIVEN_START",
            "decrease" if app_bias > 0 else "increase",
            f"Appearance points: predicted {_fmt(cpred('appearance'), 2)} vs "
            f"actual {_fmt(cact('appearance'), 2)} per player-gameweek "
            f"(bias {_fmt(app_bias, 2)}). The minutes model is the single "
            f"largest driver of xP for the majority of the player pool, so this "
            f"is the highest-leverage thing to fix. Check "
            f"MEAN_MINUTES_IF_START ({m.MEAN_MINUTES_IF_START}) and "
            f"MEAN_MINUTES_IF_SUB ({m.MEAN_MINUTES_IF_SUB}) too — they set "
            f"`minutes_share`, which scales every attacking component.",
            "high"))

    # cold-start-specific appearance error -> DEFAULT_START_PROBABILITY
    cold = results[results["is_cold_start"]]
    if len(cold) > 50:
        cold_bias = bias(cold["predicted"], cold["actual"])
        steady = results[~results["is_cold_start"]]
        steady_bias = bias(steady["predicted"], steady["actual"]) if len(steady) else float("nan")
        if np.isfinite(steady_bias) and abs(cold_bias - steady_bias) > 0.20:
            recs.append(Recommendation(
                "DEFAULT_START_PROBABILITY",
                "decrease" if cold_bias > steady_bias else "increase",
                f"Cold-start (GW1-{COLD_START_MAX_GW}) bias is "
                f"{_fmt(cold_bias, 2)} vs {_fmt(steady_bias, 2)} in steady "
                f"state — a gap of {_fmt(cold_bias - steady_bias, 2)} pts. When "
                f"there is no minutes history, every player falls back to "
                f"DEFAULT_START_PROBABILITY = {m.DEFAULT_START_PROBABILITY}, "
                f"which is applied uniformly to nailed starters and fourth-choice "
                f"squad players alike. This is exactly the position the 2026/27 "
                f"GW1 squad build is in. Consider (a) lowering the flat prior, "
                f"and (b) prioritising KNOWN DATA GAP #1 (prior-season minutes) "
                f"over any constant tuning — the fix here is more data, not a "
                f"better guess.",
                "high"))

    # --- goals ------------------------------------------------------------
    goal_bias = cbias("goals")
    if abs(goal_bias) > 0.10:
        recs.append(Recommendation(
            "XG90_PRIOR / PRIOR_WEIGHT_90S",
            "decrease" if goal_bias > 0 else "increase",
            f"Goal points: predicted {_fmt(cpred('goals'), 2)} vs actual "
            f"{_fmt(cact('goals'), 2)} (bias {_fmt(goal_bias, 2)}). If the bias "
            f"is concentrated early in the season it is PRIOR_WEIGHT_90S = "
            f"{m.PRIOR_WEIGHT_90S} pulling everyone toward XG90_PRIOR; if it is "
            f"flat across the season the positional priors themselves "
            f"({m.XG90_PRIOR}) are off. Check also ATTACK_DEFENCE_EXPONENT "
            f"({m.ATTACK_DEFENCE_EXPONENT}) and the HOME/AWAY_ATTACK_MULTIPLIER "
            f"pair, which scale every xG into a fixture-specific number.",
            "medium"))

    # --- assists ----------------------------------------------------------
    assist_bias = cbias("assists")
    if abs(assist_bias) > 0.10:
        recs.append(Recommendation(
            "XA90_PRIOR",
            "decrease" if assist_bias > 0 else "increase",
            f"Assist points: predicted {_fmt(cpred('assists'), 2)} vs actual "
            f"{_fmt(cact('assists'), 2)} (bias {_fmt(assist_bias, 2)}). Note "
            f"expected assists (xA) systematically exceeds realised assists, "
            f"because xA counts the chance created whether or not it is "
            f"converted — so a positive bias here may be a modelling choice "
            f"(use xA as-is) rather than a bad prior. Consider an explicit "
            f"xA -> assist conversion factor instead of shifting XA90_PRIOR.",
            "medium"))

    # --- clean sheets -----------------------------------------------------
    cs_bias = cbias("clean_sheet")
    if abs(cs_bias) > 0.10:
        recs.append(Recommendation(
            "LEAGUE_AVG_GOALS_CONCEDED / CLEAN_SHEET_PROB_BOUNDS",
            "decrease" if cs_bias > 0 else "increase",
            f"Clean-sheet points: predicted {_fmt(cpred('clean_sheet'), 2)} vs "
            f"actual {_fmt(cact('clean_sheet'), 2)} (bias {_fmt(cs_bias, 2)}). "
            f"P(CS) = exp(-lambda_conceded), so this is really a statement about "
            f"lambda: LEAGUE_AVG_GOALS_CONCEDED = "
            f"{m.LEAGUE_AVG_GOALS_CONCEDED}, ATTACK_DEFENCE_EXPONENT = "
            f"{m.ATTACK_DEFENCE_EXPONENT}, HOME/AWAY_CONCEDE_MULTIPLIER. "
            f"Cross-check against the goals-conceded row below: the two must "
            f"move together or the model is internally inconsistent.",
            "medium"))

    conc_bias = cbias("goals_conceded")
    if abs(conc_bias) > 0.10:
        recs.append(Recommendation(
            "LAMBDA_CONCEDED_BOUNDS / LEAGUE_AVG_GOALS_CONCEDED",
            "increase" if conc_bias > 0 else "decrease",
            f"Goals-conceded penalty: predicted {_fmt(cpred('goals_conceded'), 2)} "
            f"vs actual {_fmt(cact('goals_conceded'), 2)} (bias "
            f"{_fmt(conc_bias, 2)}; both are negative numbers, so a POSITIVE "
            f"bias means the model penalises too little). Same lambda as the "
            f"clean-sheet row — fix once, check both.",
            "medium"))

    # --- saves ------------------------------------------------------------
    gk = results[results["position"].map(normalise_position) == "GKP"]
    if len(gk) > 30:
        gk_components = decompose_actual_points(gk)
        save_pred = float(gk["xp_saves"].astype(float).mean())
        save_act = float(gk_components["saves"].mean())
        if abs(save_pred - save_act) > 0.15:
            recs.append(Recommendation(
                "SAVES_PER_GOAL_CONCEDED",
                "decrease" if save_pred > save_act else "increase",
                f"Goalkeepers only: predicted save points "
                f"{_fmt(save_pred, 2)} vs actual {_fmt(save_act, 2)} per GK "
                f"gameweek. SAVES_PER_GOAL_CONCEDED = "
                f"{m.SAVES_PER_GOAL_CONCEDED} implies a 68% league save rate; "
                f"if this is biased, that implied rate is what to re-derive.",
                "medium"))

    # --- bonus ------------------------------------------------------------
    bonus_bias = cbias("bonus")
    if abs(bonus_bias) > 0.06:
        recs.append(Recommendation(
            "BONUS_SCALE / BONUS_WEIGHT_GOAL / BONUS_POINTS_CAP",
            "decrease" if bonus_bias > 0 else "increase",
            f"Bonus: predicted {_fmt(cpred('bonus'), 3)} vs actual "
            f"{_fmt(cact('bonus'), 3)} per player-gameweek (bias "
            f"{_fmt(bonus_bias, 3)}). Bonus is a strictly zero-sum pot — exactly "
            f"6 bonus points are issued per fixture (3+2+1) — so the mean actual "
            f"bonus per player-gameweek is essentially fixed by arithmetic, "
            f"which makes this the cleanest calibration target in the whole "
            f"model. BONUS_SCALE = {m.BONUS_SCALE} is the single multiplier to "
            f"move; scale it by (actual/predicted) and re-run before touching "
            f"the individual BONUS_WEIGHT_* terms. If the bias is concentrated "
            f"in the top predicted bin, BONUS_WEIGHT_GOAL = "
            f"{m.BONUS_WEIGHT_GOAL} is over-rewarding high-xG players and "
            f"BONUS_POINTS_CAP = {m.BONUS_POINTS_CAP} is not binding early "
            f"enough.",
            "high"))

    # --- defcon -----------------------------------------------------------
    defcon_pred = cpred("defcon")
    defcon_act = cact("defcon")
    if np.isfinite(defcon_act) and defcon_act == 0.0 and defcon_pred > 0.05:
        recs.append(Recommendation(
            "DEFCON_PER90_PRIOR / DEFCON_OVERDISPERSION",
            "investigate",
            f"The model predicts {_fmt(defcon_pred, 3)} DefCon points per "
            f"player-gameweek but the archive reports zero actual DefCon points "
            f"— almost certainly because merged_gw.csv has no "
            f"`defensive_contribution` column for this season, not because "
            f"nobody hit the threshold. Confirm the column exists before "
            f"reading anything into this row; if it does not, DefCon "
            f"calibration (KNOWN DATA GAP #2) cannot be validated by this "
            f"backtest at all.",
            "low"))
    elif abs(defcon_pred - defcon_act) > 0.03 and np.isfinite(defcon_act):
        extra = ""
        if defcon and defcon.get("n", 0) > 0:
            extra = (
                f"\n\nSeparately — and more importantly — the DEFCON DATA-GAP "
                f"EXPERIMENT (section 8) shows the problem is not only the level "
                f"of the prior but the fact that it is *flat*. Replacing it with "
                f"each player's own rolling CBIT/CBIRT rate lifts the DefCon "
                f"top-50 hit rate from "
                f"{defcon['table'].loc[0, 'top50_hit_rate']:.1%} to "
                f"{defcon['table'].loc[1, 'top50_hit_rate']:.1%} and rank "
                f"correlation from {_fmt(defcon['spearman_flat'], 3)} to "
                f"{_fmt(defcon['spearman_shrunk'], 3)}. Retuning the constant "
                f"fixes the average; closing KNOWN DATA GAP #2 fixes the "
                f"ranking, which is what squad selection actually consumes.")
        recs.append(Recommendation(
            "DEFCON_PER90_PRIOR / DEFCON_OVERDISPERSION",
            "decrease" if defcon_pred > defcon_act else "increase",
            f"DefCon: predicted {_fmt(defcon_pred, 3)} vs actual "
            f"{_fmt(defcon_act, 3)} points per player-gameweek — the model "
            f"captures only "
            f"{(defcon_pred / defcon_act * 100.0) if defcon_act else float('nan'):.0f}% "
            f"of the DefCon points actually awarded, making this the "
            f"largest proportional component miss in the model.\n\n"
            f"Priors are DEFCON_PER90_PRIOR = {m.DEFCON_PER90_PRIOR} with "
            f"DEFCON_OVERDISPERSION = {m.DEFCON_OVERDISPERSION}. Measured "
            f"against this season, conditional on a player reaching 60 minutes:\n\n"
            f"| pos | model P(threshold) | actual hit rate | per-90 that would match |\n"
            f"|---|---|---|---|\n"
            f"| DEF (10+ CBIT) | 0.116 | 0.270 | ~8.6 (currently 6.5) |\n"
            f"| MID (12+ CBIRT) | 0.130 | 0.179 | ~9.3 (currently 8.5) |\n"
            f"| FWD (12+ CBIRT) | 0.015 | 0.012 | ~4.8 (currently 5.0) |\n\n"
            f"So DEF is the badly-wrong one: the prior implies defenders hit the "
            f"threshold 12% of the time when they actually do so 27% of the "
            f"time — under by more than half. MID is mildly low and FWD is "
            f"already about right. Raising DEFCON_PER90_PRIOR['DEF'] toward 8.5 "
            f"and ['MID'] toward 9.3 would align the means. Note the observed "
            f"raw league rate for defenders is 7.69 CBIT/90; the model needs a "
            f"slightly higher input than that because MEAN_MINUTES_IF_START "
            f"({m.MEAN_MINUTES_IF_START}) discounts the rate to an 80-minute "
            f"match before applying the threshold.{extra}",
            "high"))

    # --- cards ------------------------------------------------------------
    card_bias = cbias("cards")
    if abs(card_bias) > 0.05:
        recs.append(Recommendation(
            "YELLOW_PER90_PRIOR / RED_PER90_PRIOR",
            "increase" if card_bias > 0 else "decrease",
            f"Cards/own goals: predicted {_fmt(cpred('cards'), 3)} vs actual "
            f"{_fmt(cact('cards'), 3)} (both negative). The model uses flat "
            f"positional priors (KNOWN DATA GAP #3); the fix is per-player card "
            f"rates from the archive, not a different flat number.",
            "low"))

    # --- calibration shape ------------------------------------------------
    calib = calibration_table(results["predicted"], results["actual"])
    if len(calib) >= 3:
        top = calib.iloc[-1]
        bottom = calib.iloc[0]
        if top["bias"] > 0.5 and bottom["bias"] < top["bias"] - 0.5:
            recs.append(Recommendation(
                "BONUS_SCALE / ATTACK_MULTIPLIER_BOUNDS / XG90_PRIOR",
                "decrease",
                f"Calibration is not flat: the top predicted bin over-predicts "
                f"by {_fmt(top['bias'], 2)} while the bottom bin is off by "
                f"{_fmt(bottom['bias'], 2)}. The model's ceiling is too high — "
                f"it is too confident about its premium picks. Compress the top "
                f"end via BONUS_SCALE and ATTACK_MULTIPLIER_BOUNDS "
                f"({m.ATTACK_MULTIPLIER_BOUNDS}) before touching anything that "
                f"affects the whole pool.",
                "high"))
        if bottom["bias"] > 0.3:
            recs.append(Recommendation(
                "SUB_APPEARANCE_RATE / MIN_START_PROBABILITY",
                "decrease",
                f"The LOWEST predicted bin still over-predicts by "
                f"{_fmt(bottom['bias'], 2)} pts. That is the fringe-player tail: "
                f"SUB_APPEARANCE_RATE = {m.SUB_APPEARANCE_RATE} credits every "
                f"non-starter with a 30% chance of a bench cameo, which over a "
                f"few hundred fringe players adds up to a lot of phantom "
                f"appearance points. Lowering it is cheap and safe — it barely "
                f"moves the players you would actually pick.",
                "medium"))
        # The opposite failure: predictions compressed toward the middle, so the
        # model under-rates its own best picks. Costly for captaincy, where only
        # the very top of the ranking is consumed.
        if top["bias"] < -0.2 and top["bias"] < bottom["bias"] - 0.15:
            recs.append(Recommendation(
                "ATTACK_MULTIPLIER_BOUNDS / PRIOR_WEIGHT_90S / BONUS_POINTS_CAP",
                "widen the spread (increase the ceiling)",
                f"Calibration is monotone but **compressed**: the bottom "
                f"predicted bin is nearly unbiased ({_fmt(bottom['bias'], 2)}) "
                f"while the top bin under-predicts by "
                f"{_fmt(abs(top['bias']), 2)} pts "
                f"(predicted {_fmt(top['mean_pred'], 2)} vs actual "
                f"{_fmt(top['mean_actual'], 2)}). The model is not wrong about "
                f"who the good players are — the ranking is fine — it is too "
                f"timid about how good they are.\n\n"
                f"Three constants pull the top end down, in decreasing order of "
                f"likely impact:\n\n"
                f"1. `PRIOR_WEIGHT_90S = {m.PRIOR_WEIGHT_90S}` shrinks every "
                f"player's xG/xA rate toward a league-average positional prior "
                f"with the weight of {m.PRIOR_WEIGHT_90S:.0f} full matches. For "
                f"an elite forward with a genuinely elite rate this is a "
                f"permanent haircut that never fully washes out. Consider "
                f"lowering it, or making it decay as the sample grows.\n"
                f"2. `BONUS_POINTS_CAP = {m.BONUS_POINTS_CAP}` hard-caps bonus, "
                f"which binds exactly on the premium players in this bin.\n"
                f"3. `ATTACK_MULTIPLIER_BOUNDS = {m.ATTACK_MULTIPLIER_BOUNDS}` "
                f"caps how favourable a fixture can be.\n\n"
                f"This matters more than its size suggests: captaincy consumes "
                f"only the very top of the ranking, so a systematic "
                f"{_fmt(abs(top['bias']), 2)}-point under-estimate of the best "
                f"players is concentrated exactly where the decisions are.",
                "medium"))

    # --- per-position level ----------------------------------------------
    if "position" in results.columns:
        pos_norm = results["position"].map(normalise_position)
        worst_pos, worst_bias, worst_n = None, 0.0, 0
        for p in POSITIONS:
            sl = results[pos_norm == p]
            if len(sl) < 200:
                continue
            b = bias(sl["predicted"], sl["actual"])
            if np.isfinite(b) and abs(b) > abs(worst_bias):
                worst_pos, worst_bias, worst_n = p, b, len(sl)
        if worst_pos and abs(worst_bias) > 0.25:
            knob = {"GKP": "SAVES_PER_GOAL_CONCEDED / CLEAN_SHEET_PROB_BOUNDS",
                    "DEF": "DEFCON_PER90_PRIOR['DEF'] / CLEAN_SHEET_PROB_BOUNDS",
                    "MID": "XG90_PRIOR['MID'] / XA90_PRIOR['MID']",
                    "FWD": "XG90_PRIOR['FWD'] / PRIOR_WEIGHT_90S"}[worst_pos]
            recs.append(Recommendation(
                knob,
                "decrease" if worst_bias > 0 else "increase",
                f"{worst_pos} is the worst-calibrated position on the credible "
                f"pool: bias {_fmt(worst_bias, 3)} pts per player-gameweek over "
                f"{worst_n:,} observations, against an all-position bias of "
                f"{_fmt(bias(results['predicted'], results['actual']), 3)}. "
                f"For FWD specifically, note that XG90_PRIOR['FWD'] = "
                f"{m.XG90_PRIOR['FWD']} is a league-average forward, but the "
                f"forwards anyone actually owns are well above average — so the "
                f"shrinkage in `shrunk_per90_rate()` drags exactly the players "
                f"that matter toward a prior that does not describe them. "
                f"Consider whether the prior should be conditioned on price or "
                f"minutes rather than position alone.",
                "medium"))

    if not recs:
        recs.append(Recommendation(
            "(none)", "investigate",
            "No component showed a bias above the reporting thresholds. Either "
            "the model is well calibrated on this sample or the sample is too "
            "small/too synthetic to resolve one.", "low"))
    return recs



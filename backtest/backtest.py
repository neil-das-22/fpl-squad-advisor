# 6. COMPONENT ATTRIBUTION — where the error actually comes from
# ---------------------------------------------------------------------------

def decompose_actual_points(results: pd.DataFrame) -> pd.DataFrame:
    """Split each player's REAL gameweek score into FPL's scoring components.

    Mirrors the `xp_*` component columns the model emits, so predicted and
    actual can be compared component by component. That is what turns "the model
    is 0.4 points high" into "the model is 0.4 points high *on bonus*", which is
    the difference between a vague finding and an actionable one.

    A `residual` column captures whatever the decomposition does not explain
    (chiefly DefCon in seasons where the archive lacks the column). If the mean
    residual is not close to zero, treat the component table with suspicion —
    it means the archive's columns do not add up to `total_points`.
    """
    out = pd.DataFrame(index=results.index)
    pos = results["position"].map(normalise_position)
    mins = results["minutes"].astype(float)

    out["appearance"] = np.where(mins >= 60, 2.0, np.where(mins > 0, 1.0, 0.0))
    out["goals"] = results["goals_scored"].astype(float) * pos.map(m.GOAL_POINTS)
    out["assists"] = results["assists"].astype(float) * m.ASSIST_POINTS
    out["clean_sheet"] = np.where(
        mins >= 60,
        results["clean_sheets"].astype(float) * pos.map(m.CLEAN_SHEET_POINTS),
        0.0)

    conceded = results["goals_conceded"].astype(float)
    out["goals_conceded"] = np.where(
        pos.isin(["GKP", "DEF"]),
        m.CONCEDED_PENALTY_PER_N[0] * np.floor(conceded / m.CONCEDED_PENALTY_PER_N[1]),
        0.0)

    saves = results["saves"].astype(float)
    out["saves"] = np.where(
        pos == "GKP",
        m.SAVE_POINTS_PER_N_SAVES[0] * np.floor(saves / m.SAVE_POINTS_PER_N_SAVES[1]),
        0.0)

    out["cards"] = (m.YELLOW_CARD_POINTS * results["yellow_cards"].astype(float)
                    + m.RED_CARD_POINTS * results["red_cards"].astype(float)
                    + m.OWN_GOAL_POINTS * results["own_goals"].astype(float))
    out["penalties"] = (
        m.PENALTY_SAVE_POINTS * results.get("penalties_saved", 0.0)
        + m.PENALTY_MISS_POINTS * results.get("penalties_missed", 0.0))
    out["bonus"] = results["bonus"].astype(float)

    # DefCon: 2025/26+ archives carry a `defensive_contribution` column. Whether
    # it holds POINTS (0/2) or the raw CBIT/CBIRT COUNT varies by dump, so sniff
    # it rather than assume. Flagged in the report either way.
    out["defcon"] = 0.0
    if "defensive_contribution" in results.columns:
        dc = results["defensive_contribution"].astype(float)
        if dc.max() <= 2.0:
            out["defcon"] = dc                      # already points
        else:
            thresholds = pos.map(m.DEFCON_THRESHOLD).astype(float)
            out["defcon"] = np.where(
                thresholds.notna() & (dc >= thresholds), float(m.DEFCON_POINTS), 0.0)

    explained = out.sum(axis=1)
    out["residual"] = results["actual"].astype(float) - explained
    return out


_COMPONENT_PAIRS = [
    ("appearance", "xp_appearance"),
    ("goals", "xp_goals"),
    ("assists", "xp_assists"),
    ("clean_sheet", "xp_clean_sheet"),
    ("goals_conceded", "xp_goals_conceded"),
    ("saves", "xp_saves"),
    ("defcon", "xp_defcon"),
    ("cards", "xp_cards"),
    ("penalties", "xp_penalties"),
    ("bonus", "xp_bonus"),
]


def component_comparison(results: pd.DataFrame) -> pd.DataFrame:
    """Mean predicted vs mean actual points, one row per scoring component."""
    actual_components = decompose_actual_points(results)
    rows = []
    for name, xp_col in _COMPONENT_PAIRS:
        if xp_col not in results.columns:
            continue
        pred_mean = float(results[xp_col].astype(float).mean())
        act_mean = float(actual_components[name].mean())
        rows.append({
            "component": name,
            "mean_pred": pred_mean,
            "mean_actual": act_mean,
            "bias": pred_mean - act_mean,
            "pct_of_pred": pred_mean,
        })
    rows.append({
        "component": "unexplained_residual",
        "mean_pred": float("nan"),
        "mean_actual": float(actual_components["residual"].mean()),
        "bias": float("nan"),
        "pct_of_pred": float("nan"),
    })
    df = pd.DataFrame(rows)
    total_pred = df["mean_pred"].sum(skipna=True)
    df["pct_of_pred"] = df["mean_pred"] / total_pred * 100.0 if total_pred else np.nan
    return df



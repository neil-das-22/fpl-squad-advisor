"""
Backtest harness for models/xp_model.py — historical validation of the xP model.

WHAT THIS IS
------------
Validation infrastructure. It replays a completed Premier League season one
gameweek at a time, asks `xp_model.calculate_xp_for_gameweek()` what it would
have predicted using ONLY information available before that gameweek kicked
off, and scores those predictions against what actually happened.

It is deliberately a *diagnostic* pass, not a tuning pass. Nothing in this file
imports-and-mutates xp_model constants. The output is a report that names the
constants that look miscalibrated and in which direction, for a human to decide
on.

DATA SOURCE
-----------
vaastav/Fantasy-Premier-League, the standard public FPL archive. Expected at:

    data/raw/historical_2025_26/merged_gw.csv    <- ground truth, per GW per player
    data/raw/historical_2025_26/players_raw.csv  <- season roster (id/name/pos/team)
    data/raw/historical_2025_26/teams.csv        <- team strength ratings
    data/raw/historical_2025_26/fixtures.csv     <- fixtures + FDR + results

This sandbox cannot reach github.com, so those files are dropped in manually.
If they are absent the harness runs in SYNTHETIC SELF-TEST MODE against a
simulated season generated by `make_synthetic_dataset()` — same schema, fake
football. That mode proves the plumbing works; it says NOTHING about the real
model's accuracy, and every line of output is labelled as such.

NO-LOOKAHEAD GUARANTEE (the single most important property here)
---------------------------------------------------------------
Everything the model sees for gameweek N is derived from exactly one frame:

    history = gw_df[gw_df["gw"] < N]        # aggregate_prior_history(), line 1

`aggregate_prior_history()` takes that slice as its first statement and no other
function that builds model inputs is allowed to touch the unfiltered gameweek
table. Specifically:

  * Cumulative minutes/starts/goals/assists/xG/xA/bonus/bps come from `history`.
  * Player price comes from the LAST PRIOR gameweek's `value` (not from
    players_raw.csv, whose `now_cost` is an end-of-season snapshot).
  * Fixture inputs for GW N use only `team_h`, `team_a`, `team_h_difficulty`,
    `team_a_difficulty`. FPL sets difficulty before the season; scores and
    `finished` are explicitly DROPPED in `build_fixtures_frame()` so they cannot
    leak in even by accident.
  * Ground truth is read by a separate function, `get_actual_points()`, which is
    the only place in the file that filters `gw == N` for OUTCOMES.
  * Baselines are also history-only (see `build_baselines()`).

  ONE DELIBERATE EXCEPTION, and it is not a leak: `fpl_official_xp()` reads the
  `xP` column from the `gw == N` rows. That column is FPL's own *pre-match*
  projection (their `ep_this`), snapshotted by the archive next to the result —
  a rival prediction, not an outcome. It is used only as a comparison baseline,
  never as a model input, and is excluded from `_CUMULATIVE_COLUMNS`. See that
  function's docstring.

BASELINES COMPARED AGAINST
--------------------------
  zero          -- always predict 0 (surprisingly strong on MAE; see report).
  season PPG    -- the player's own season-to-date points per gameweek.
  position mean -- mean points for that position so far.
  FPL official  -- FPL's own published xP. Not naive: a serious rival model with
                   access to team news we do not have. NOTE this column is
                   populated for only 11 of 38 gameweeks in the 2025/26 dump;
                   all-zero rounds are treated as MISSING, not as a prediction
                   of nil, and both sides are scored on the surviving subset.

DEFCON DATA-GAP EXPERIMENT
--------------------------
`defcon_experiment()` quantifies what xp_model's KNOWN DATA GAP #2 costs. The
live model has no CBIT/CBIRT feed and falls back to a flat positional constant;
this archive has the real counts, so we rebuild each player's own rolling rate
from prior gameweeks and re-score the DefCon component alone. Headline: the gain
is in ranking, not in mean error. See report section 8.

`test_backtest.py::test_no_lookahead_leakage` proves this empirically by
corrupting every gameweek >= N and asserting the reconstructed pre-GW-N state
and the resulting predictions are bit-identical.

KNOWN, UNAVOIDABLE LIMITATIONS (read these before trusting a number)
--------------------------------------------------------------------
  1. `teams.csv` in the archive is a single end-of-season snapshot of FPL's
     strength ratings. FPL nudges those ratings during the season, so the
     fixture model gets very slightly better team ratings than it would have had
     live. This inflates the model's apparent skill a little. It is the one
     lookahead we cannot remove without a per-gameweek strength history.
  2. Injury/availability status is not reconstructible per gameweek from the
     archive, so every player is backtested as `status = "a"`. Live, the model
     zeroes out injured players. The backtest therefore *understates* live
     accuracy: it happily predicts 4.5 xP for someone who was actually out.
     This shows up as over-prediction and is called out in the report.
  3. `is_promoted` is set False for everyone — the promoted-club fallback path
     (PROMOTED_* constants) is NOT exercised by this backtest.
  4. Penalty duty and per-player DefCon rates are not supplied (KNOWN DATA GAPS
     #2 and #4 in xp_model), so those components run on positional priors, which
     is exactly how they run live today.

USAGE
-----
    python3 backtest/backtest.py                 # auto: real data if present, else synthetic
    python3 backtest/backtest.py --synthetic     # force synthetic self-test
    python3 backtest/backtest.py --from-gw 1 --to-gw 38
    python3 backtest/backtest.py --data-dir /some/other/season
"""


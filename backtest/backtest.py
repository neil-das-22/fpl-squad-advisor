def _clean_pair(pred, actual) -> tuple[np.ndarray, np.ndarray]:
    p = np.asarray(pred, dtype=float)
    a = np.asarray(actual, dtype=float)
    ok = np.isfinite(p) & np.isfinite(a)
    return p[ok], a[ok]


def mae(pred, actual) -> float:
    p, a = _clean_pair(pred, actual)
    return float("nan") if len(p) == 0 else float(np.mean(np.abs(p - a)))


def rmse(pred, actual) -> float:
    p, a = _clean_pair(pred, actual)
    return float("nan") if len(p) == 0 else float(np.sqrt(np.mean((p - a) ** 2)))


def bias(pred, actual) -> float:
    """Mean signed error. Positive = the model over-predicts."""
    p, a = _clean_pair(pred, actual)
    return float("nan") if len(p) == 0 else float(np.mean(p - a))


def pearson(pred, actual) -> float:
    """Pearson r, computed directly so the harness has no scipy dependency."""
    p, a = _clean_pair(pred, actual)
    if len(p) < 2 or np.std(p) == 0 or np.std(a) == 0:
        return float("nan")
    return float(np.corrcoef(p, a)[0, 1])


def spearman(pred, actual) -> float:
    """Spearman rho = Pearson r on average-tied ranks (no scipy needed).

    Rank correlation is the metric that matters most here: squad selection only
    ever asks "is this player better than that one", never "is 5.2 exactly right".
    """
    p, a = _clean_pair(pred, actual)
    if len(p) < 2:
        return float("nan")
    rp = pd.Series(p).rank(method="average").to_numpy()
    ra = pd.Series(a).rank(method="average").to_numpy()
    if np.std(rp) == 0 or np.std(ra) == 0:
        return float("nan")
    return float(np.corrcoef(rp, ra)[0, 1])


def calibration_table(pred, actual, n_bins: int = N_CALIBRATION_BINS) -> pd.DataFrame:
    """Quantile-bin by predicted xP and compare mean predicted vs mean actual.

    Quantile bins rather than equal-width: the predicted-xP distribution is
    heavily right-skewed (hundreds of near-zero fringe players, a handful of
    premiums), so equal-width bins would put ~95% of rows in bin 1 and tell us
    nothing about the top end — which is the end that matters.
    """
    p, a = _clean_pair(pred, actual)
    if len(p) < n_bins:
        return pd.DataFrame()
    df = pd.DataFrame({"pred": p, "actual": a})
    try:
        df["bin"] = pd.qcut(df["pred"], n_bins, labels=False, duplicates="drop")
    except ValueError:
        return pd.DataFrame()
    rows = []
    for b, grp in df.groupby("bin"):
        rows.append({
            "bin": int(b) + 1,
            "n": int(len(grp)),
            "pred_range": f"{grp['pred'].min():.2f}-{grp['pred'].max():.2f}",
            "mean_pred": float(grp["pred"].mean()),
            "mean_actual": float(grp["actual"].mean()),
            "bias": float(grp["pred"].mean() - grp["actual"].mean()),
        })
    return pd.DataFrame(rows)


def top_n_precision(results: pd.DataFrame, pred_col: str = "predicted",
                    n: int = TOP_N, threshold: float = TOP_N_THRESHOLD
                    ) -> dict[str, float]:
    """Of the model's top-N picks each gameweek, what fraction hauled?

    This is the metric that maps onto the actual job. A model can have a
    mediocre MAE and still be extremely useful if its top-20 shortlist is full
    of players who return. Reported alongside the mean points those picks
    actually scored, and the pool-wide hit rate for context (a top-N precision
    below the pool rate means the shortlist is worse than random).
    """
    hits, picks, points, gws = 0, 0, 0.0, 0
    for _, grp in results.groupby("gameweek"):
        playable = grp[~grp["blank"]] if "blank" in grp.columns else grp
        if len(playable) == 0:
            continue
        top = playable.nlargest(n, pred_col)
        hits += int((top["actual"] >= threshold).sum())
        picks += len(top)
        points += float(top["actual"].sum())
        gws += 1
    pool_rate = float((results["actual"] >= threshold).mean()) if len(results) else float("nan")
    return {
        "precision": hits / picks if picks else float("nan"),
        "mean_actual_points": points / picks if picks else float("nan"),
        "pool_hit_rate": pool_rate,
        "gameweeks": gws,
        "picks": picks,
    }


def metric_block(results: pd.DataFrame, pred_col: str = "predicted") -> dict[str, float]:
    """The standard bundle of accuracy metrics for one slice of the results."""
    if len(results) == 0:
        return {"n": 0}
    p, a = results[pred_col], results["actual"]
    return {
        "n": int(len(results)),
        "mae": mae(p, a),
        "rmse": rmse(p, a),
        "bias": bias(p, a),
        "pearson": pearson(p, a),
        "spearman": spearman(p, a),
        "mean_pred": float(np.mean(p)),
        "mean_actual": float(np.mean(a)),
    }



def _f(x: Any, default: float = 0.0) -> float:
    """Tolerant float coercion (the archive stores plenty of numbers as text)."""
    return m._to_float(x, default)


def _find_column(df: pd.DataFrame, candidates: tuple[str, ...]) -> str | None:
    """First matching column name, tried exactly then case-insensitively."""
    for cand in candidates:
        if cand in df.columns:
            return cand
    lowered = {str(c).lower(): c for c in df.columns}
    for cand in candidates:
        if cand.lower() in lowered:
            return lowered[cand.lower()]
    return None


def normalise_position(value: Any) -> str:
    """'GK'/1/'Goalkeeper' -> 'GKP'. Anything unrecognised -> 'MID'."""
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "MID"
    key = str(value).strip().upper()
    if key.endswith(".0"):          # element_type read back as 1.0
        key = key[:-2]
    return _POSITION_ALIASES.get(key, "MID")


def _as_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    s = str(value).strip().lower()
    return s in ("true", "1", "t", "yes", "y")


def gameweeks_with_fpl_xp(gw_df: pd.DataFrame, min_nonzero_frac: float = 0.10
                          ) -> list[int]:
    """Gameweeks where FPL's own `xP` column actually carries data.

    In the 2025/26 archive this column is populated for only a handful of
    rounds; for the rest every player is written as 0.0. A round of all-zeros is
    a scraper gap, not FPL predicting that nobody will score, so it must be
    excluded rather than scored — otherwise the FPL baseline gets a fictitious
    MAE of ~1.1 and our model "wins" a comparison that never happened.

    A legitimately-populated round still contains plenty of genuine zeros (FPL
    projects 0.0 for players it expects not to feature), hence a low threshold:
    we are separating "mostly zeros" from "entirely zeros".
    """
    if "fpl_xp" not in gw_df.columns or len(gw_df) == 0:
        return []
    frac = gw_df.groupby("gw")["fpl_xp"].apply(
        lambda s: float((pd.to_numeric(s, errors="coerce").fillna(0.0) != 0).mean()))
    return sorted(int(g) for g, f in frac.items() if f >= min_nonzero_frac)



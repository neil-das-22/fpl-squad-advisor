_SYNTH_TEAMS = [
    # name, short, attack, defence  (raw strength scale, same units as FPL's)
    ("Alderton",  "ALD", 1340, 1330),
    ("Brixmoor",  "BRX", 1300, 1290),
    ("Caldwell",  "CAL", 1240, 1210),
    ("Draymouth", "DRY", 1190, 1180),
    ("Estwood",   "EST", 1150, 1160),
    ("Fenbury",   "FEN", 1120, 1100),
    ("Garrowby",  "GAR", 1070, 1060),
    ("Hallowfen", "HAL", 1020, 1010),
]

_SQUAD_TEMPLATE = [
    # (position, n_players, base start probability, xg90, xa90)
    ("GKP", 2, [0.92, 0.10], [0.00, 0.00], [0.01, 0.00]),
    ("DEF", 6, [0.90, 0.86, 0.82, 0.70, 0.35, 0.15],
     [0.09, 0.06, 0.05, 0.04, 0.03, 0.02],
     [0.10, 0.08, 0.06, 0.05, 0.03, 0.02]),
    ("MID", 6, [0.90, 0.85, 0.78, 0.62, 0.35, 0.15],
     [0.38, 0.22, 0.14, 0.10, 0.07, 0.05],
     [0.30, 0.20, 0.14, 0.10, 0.07, 0.05]),
    ("FWD", 3, [0.88, 0.55, 0.20],
     [0.60, 0.35, 0.22],
     [0.18, 0.12, 0.09]),
]


def make_synthetic_dataset(out_dir: str, n_gameweeks: int = 14,
                           seed: int = 20260809) -> str:
    """Simulate a small season and write it out in vaastav CSV format.

    Why simulate rather than mock: the ground truth is generated by applying the
    REAL FPL scoring rules to simulated match events, so the harness's actual-
    points decomposition, its metrics and its calibration logic all have
    something structurally correct to chew on. There is genuine signal (good
    players really do score more), so correlations come out non-degenerate and a
    broken metric shows up as an obviously wrong number rather than noise.

    The schema written here is the harness's best understanding of vaastav's
    2025-26 dump. Anything the real files do differently should surface in
    `HistoricalData.warnings` when they land.

    Deliberate edge cases baked in:
      * GW1-5 have no prior history at all -> exercises the cold-start path.
      * One fixture is removed from GW9 -> two clubs get a BLANK gameweek.
      * One extra fixture is added in GW11 -> two clubs get a DOUBLE gameweek.
      * Every player has a row in every gameweek, including 0-minute rows,
        which is how merged_gw.csv behaves.
    """
    rng = np.random.default_rng(seed)
    os.makedirs(out_dir, exist_ok=True)

    # --- teams ------------------------------------------------------------
    teams_rows = []
    for tid, (name, short, att, dfn) in enumerate(_SYNTH_TEAMS, start=1):
        teams_rows.append({
            "id": tid, "name": name, "short_name": short,
            "strength": int(np.clip(round((att - 950) / 100), 1, 5)),
            "strength_overall_home": att, "strength_overall_away": att - 20,
            "strength_attack_home": att, "strength_attack_away": att - 20,
            "strength_defence_home": dfn, "strength_defence_away": dfn - 20,
        })
    teams = pd.DataFrame(teams_rows)
    teams.to_csv(os.path.join(out_dir, "teams.csv"), index=False)
    n_teams = len(teams)

    def difficulty_for(opponent_id: int) -> int:
        att = _SYNTH_TEAMS[opponent_id - 1][2]
        return int(np.clip(round((att - 1000) / 80), 1, 5))

    # --- players ----------------------------------------------------------
    players = []
    pid = 0
    for tid, (team_name, short, _, _) in enumerate(_SYNTH_TEAMS, start=1):
        for pos, count, starts, xgs, xas in _SQUAD_TEMPLATE:
            for i in range(count):
                pid += 1
                players.append({
                    "id": pid,
                    "first_name": f"P{pid}",
                    "second_name": f"{team_name}{pos}{i + 1}",
                    "web_name": f"{short}_{pos}{i + 1}",
                    "element_type": {"GKP": 1, "DEF": 2, "MID": 3, "FWD": 4}[pos],
                    "team": tid,
                    "position": pos,
                    "now_cost": int(40 + 60 * xgs[i] + 20 * starts[i]),
                    # latent truth, used by the simulator, NOT written to CSV
                    "_p_start": starts[i],
                    "_xg90": xgs[i],
                    "_xa90": xas[i],
                })
    players = pd.DataFrame(players)

    # --- fixtures ---------------------------------------------------------
    fixture_rows = []
    fid = 0
    order = list(range(1, n_teams + 1))
    for gw in range(1, n_gameweeks + 1):
        rng.shuffle(order)
        pairs = [(order[i], order[i + 1]) for i in range(0, n_teams, 2)]
        if gw == 9:
            pairs = pairs[:-1]                      # BLANK gameweek for 2 clubs
        for home, away in pairs:
            fid += 1
            fixture_rows.append({
                "id": fid, "event": gw, "team_h": home, "team_a": away,
                "team_h_difficulty": difficulty_for(away),
                "team_a_difficulty": difficulty_for(home),
                "kickoff_time": f"2025-{8 + gw // 5:02d}-{1 + (gw * 3) % 27:02d}T15:00:00Z",
                "finished": True,
            })
        if gw == 11:
            fid += 1
            h, a = pairs[0]
            fixture_rows.append({                    # DOUBLE gameweek for 2 clubs
                "id": fid, "event": gw, "team_h": a, "team_a": h,
                "team_h_difficulty": difficulty_for(h),
                "team_a_difficulty": difficulty_for(a),
                "kickoff_time": f"2025-11-2{gw % 8}T20:00:00Z",
                "finished": True,
            })
    fixtures = pd.DataFrame(fixture_rows)

    # --- simulate every fixture ------------------------------------------
    team_name_by_id = dict(zip(teams["id"], teams["name"]))
    att_by_id = {tid: _SYNTH_TEAMS[tid - 1][2] for tid in teams["id"]}
    def_by_id = {tid: _SYNTH_TEAMS[tid - 1][3] for tid in teams["id"]}
    players_by_team = {tid: grp for tid, grp in players.groupby("team")}

    gw_rows: list[dict[str, Any]] = []
    fixture_scores: dict[int, tuple[int, int]] = {}

    for _, fx in fixtures.iterrows():
        fid = int(fx["id"])
        gw = int(fx["event"])
        sides = [(int(fx["team_h"]), int(fx["team_a"]), True),
                 (int(fx["team_a"]), int(fx["team_h"]), False)]

        per_side: dict[int, list[dict[str, Any]]] = {}
        goals_by_team: dict[int, int] = {}

        for own, opp, is_home in sides:
            strength_ratio = (att_by_id[own] / def_by_id[opp]) ** 1.4
            attack_mult = strength_ratio * (1.10 if is_home else 0.92)
            rows = []
            team_goals = 0
            for _, pl in players_by_team[own].iterrows():
                started = rng.random() < pl["_p_start"]
                if started:
                    minutes = int(rng.choice([90, 90, 90, 85, 72, 64, 46],
                                             p=[.42, .18, .12, .10, .08, .06, .04]))
                else:
                    minutes = int(rng.choice([0, 0, 0, 25, 15, 8],
                                             p=[.55, .12, .08, .10, .09, .06]))
                share = minutes / 90.0
                lam_g = pl["_xg90"] * share * attack_mult
                lam_a = pl["_xa90"] * share * attack_mult
                goals = int(rng.poisson(lam_g)) if lam_g > 0 else 0
                assists = int(rng.poisson(lam_a)) if lam_a > 0 else 0
                team_goals += goals
                rows.append({
                    "element": int(pl["id"]),
                    "name": pl["web_name"],
                    "position": pl["position"],
                    "team": team_name_by_id[own],
                    "GW": gw,
                    "round": gw,
                    "fixture": fid,
                    "opponent_team": opp,
                    "was_home": bool(is_home),
                    "minutes": minutes,
                    "starts": int(started),
                    "goals_scored": goals,
                    "assists": assists,
                    # xG/xA are noisy observations of the same latent rate.
                    "expected_goals": round(float(rng.gamma(2.0, max(lam_g, 1e-4) / 2.0)), 2),
                    "expected_assists": round(float(rng.gamma(2.0, max(lam_a, 1e-4) / 2.0)), 2),
                    "yellow_cards": int(rng.random() < 0.11 * share),
                    "red_cards": int(rng.random() < 0.006 * share),
                    "own_goals": int(rng.random() < 0.004 * share),
                    "penalties_missed": 0,
                    "penalties_saved": 0,
                    "value": int(pl["now_cost"]),
                    "_pos": pl["position"],
                })
            per_side[own] = rows
            goals_by_team[own] = team_goals

        h, a = int(fx["team_h"]), int(fx["team_a"])
        fixture_scores[fid] = (goals_by_team[h], goals_by_team[a])

        for own, opp, is_home in sides:
            conceded = goals_by_team[opp]
            for row in per_side[own]:
                pos = row.pop("_pos")
                mins = row["minutes"]
                row["team_h_score"] = goals_by_team[h]
                row["team_a_score"] = goals_by_team[a]
                row["goals_conceded"] = conceded if mins > 0 else 0
                row["clean_sheets"] = int(mins >= 60 and conceded == 0)
                row["saves"] = (int(rng.poisson(2.1 * max(conceded, 0.6) * mins / 90.0))
                                if pos == "GKP" else 0)
                row["expected_goals_conceded"] = round(conceded * 0.9 + 0.3, 2)
                row["defensive_contribution"] = (
                    int(rng.poisson({"GKP": 0.4, "DEF": 6.5, "MID": 7.5,
                                     "FWD": 4.0}[pos] * mins / 90.0)))
                # points from the real FPL rules
                pts = 0
                if mins >= 60:
                    pts += 2
                elif mins > 0:
                    pts += 1
                pts += row["goals_scored"] * m.GOAL_POINTS[pos]
                pts += row["assists"] * m.ASSIST_POINTS
                pts += row["clean_sheets"] * m.CLEAN_SHEET_POINTS[pos]
                if pos in ("GKP", "DEF"):
                    pts -= row["goals_conceded"] // 2
                if pos == "GKP":
                    pts += row["saves"] // 3
                threshold = m.DEFCON_THRESHOLD[pos]
                if threshold is not None and row["defensive_contribution"] >= threshold:
                    pts += m.DEFCON_POINTS
                pts -= row["yellow_cards"]
                pts -= 3 * row["red_cards"]
                pts -= 2 * row["own_goals"]
                row["_base_points"] = pts
                row["bps"] = int(
                    (3 if mins >= 60 else (1 if mins > 0 else 0))
                    + 24 * row["goals_scored"] + 9 * row["assists"]
                    + 12 * row["clean_sheets"] + 2 * row["saves"]
                    - 3 * row["yellow_cards"])
                row["influence"] = round(row["bps"] * 0.6, 1)
                row["creativity"] = round(row["assists"] * 20.0 + mins * 0.08, 1)
                row["threat"] = round(row["goals_scored"] * 30.0 + mins * 0.1, 1)
                row["ict_index"] = round(
                    (row["influence"] + row["creativity"] + row["threat"]) / 10.0, 1)

        # bonus: 3/2/1 to the top three bps in the fixture (players only)
        everyone = [r for side in per_side.values() for r in side if r["minutes"] > 0]
        everyone.sort(key=lambda r: (-r["bps"], r["element"]))
        for r in everyone:
            r["bonus"] = 0
        for award, r in zip((3, 2, 1), everyone[:3]):
            r["bonus"] = award
        for side in per_side.values():
            for r in side:
                r.setdefault("bonus", 0)
                r["total_points"] = r.pop("_base_points") + r["bonus"]
                gw_rows.append(r)

    merged = pd.DataFrame(gw_rows)
    # vaastav's column order, roughly — order should not matter to the loader,
    # which is part of what this exercises.
    merged = merged.sort_values(["GW", "element"]).reset_index(drop=True)
    merged.to_csv(os.path.join(out_dir, "merged_gw.csv"), index=False)

    fixtures["team_h_score"] = fixtures["id"].map(lambda i: fixture_scores[i][0])
    fixtures["team_a_score"] = fixtures["id"].map(lambda i: fixture_scores[i][1])
    fixtures.to_csv(os.path.join(out_dir, "fixtures.csv"), index=False)

    # players_raw: END-OF-SEASON totals, exactly like the real file. The loader
    # must ignore every one of these stat columns (they are pure lookahead).
    season = merged.groupby("element").agg(
        total_points=("total_points", "sum"),
        minutes=("minutes", "sum"),
        goals_scored=("goals_scored", "sum"),
        assists=("assists", "sum"),
    )
    players_raw = players.drop(columns=["_p_start", "_xg90", "_xa90", "position"])
    players_raw = players_raw.merge(season, left_on="id", right_index=True, how="left")
    players_raw.to_csv(os.path.join(out_dir, "players_raw.csv"), index=False)

    return out_dir


def load_synthetic_dataset(tmp_dir: str | None = None, **kwargs) -> HistoricalData:
    """Generate a synthetic season and load it back through the REAL loader.

    Round-tripping through CSV and `load_historical_gw_data()` is deliberate: it
    means synthetic mode exercises the same parsing/normalisation code path the
    real data will hit, so a bug in the loader cannot hide behind hand-built
    in-memory frames.
    """
    tmp_dir = tmp_dir or tempfile.mkdtemp(prefix="fpl_backtest_synth_")
    make_synthetic_dataset(tmp_dir, **kwargs)
    hist = load_historical_gw_data(tmp_dir)
    hist.source = "synthetic"
    hist.warnings.insert(
        0, "SYNTHETIC SELF-TEST MODE — simulated season, not real football.")
    return hist



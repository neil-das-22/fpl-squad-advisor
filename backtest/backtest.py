def aggregate_prior_history(gw_df: pd.DataFrame, target_gw: int) -> pd.DataFrame:
    """Season-to-date totals for every player, using gameweeks 1..target_gw-1.

    *** THIS IS THE LEAKAGE FIREWALL. ***

    The first statement slices the gameweek table to strictly-earlier rounds and
    every subsequent line reads only that slice. If you need a new feature, it
    must be derived from `history` inside this function — do not reach back into
    `gw_df` anywhere downstream.

    Returns:
        DataFrame indexed by `element` with cumulative `minutes`, `starts`,
        `goals_scored`, `assists`, `expected_goals`, ... plus:
            n_gws_available  -- how many gameweeks of the season have elapsed
            n_appearances    -- rounds in which the player recorded any minutes
            last_value       -- most recent price (in FPL tenths of a million)
            last_team        -- club as of the most recent prior round
            position         -- most recent recorded position
    """
    history = gw_df[gw_df["gw"] < int(target_gw)]           # <-- the firewall
    n_prior_rounds = int(target_gw) - 1

    if len(history) == 0:
        return pd.DataFrame(
            columns=list(_CUMULATIVE_COLUMNS)
            + ["n_gws_available", "n_appearances", "last_value", "last_team",
               "position"]
        ).rename_axis("element")

    agg = history.groupby("element")[list(_CUMULATIVE_COLUMNS)].sum()
    agg["n_gws_available"] = n_prior_rounds
    agg["n_appearances"] = history.assign(
        played=(history["minutes"] > 0).astype(int)
    ).groupby("element")["played"].sum()

    # Latest-known price / club / position: sort by gameweek and take the tail.
    ordered = history.sort_values(["element", "gw"])
    last = ordered.groupby("element").tail(1).set_index("element")
    agg["last_value"] = last["value"] if "value" in last.columns else 0.0
    agg["last_team"] = last["team"] if "team" in last.columns else None
    agg["position"] = (last["position"].map(normalise_position)
                       if "position" in last.columns else "MID")

    return agg


def build_players_frame(hist: HistoricalData, prior: pd.DataFrame,
                        target_gw: int) -> pd.DataFrame:
    """Assemble a players_df in exactly the shape load_players_df() emits.

    The player universe is the union of
      (a) everyone who has appeared in the archive before `target_gw`, and
      (b) the season roster from players_raw.csv.
    (b) is what makes GW1 possible at all: pre-season you know the roster but
    have no match data, which is precisely the cold-start situation the 2026/27
    season opens with. Knowing who is registered is not lookahead — it is
    bootstrap-static, available before a ball is kicked.
    """
    roster = hist.players_raw.set_index("id")
    ids = sorted(set(prior.index.tolist()) | set(roster.index.tolist()))

    rows: list[dict[str, Any]] = []
    for pid in ids:
        p = prior.loc[pid] if pid in prior.index else None
        r = roster.loc[pid] if pid in roster.index else None
        if isinstance(r, pd.DataFrame):        # duplicate ids in players_raw
            r = r.iloc[0]

        # Club as of this gameweek: last known from history, else roster.
        team_name = None
        if p is not None and isinstance(p.get("last_team"), str):
            team_name = p["last_team"]
        if not team_name and r is not None:
            team_name = r.get("team_name")
        if not isinstance(team_name, str) or not team_name:
            continue                            # club-less -> cannot be fixtured

        position = None
        if r is not None:
            position = r.get("position")
        if not position and p is not None:
            position = p.get("position")
        position = normalise_position(position)

        minutes = _f(p["minutes"]) if p is not None else 0.0
        starts = _f(p["starts"]) if p is not None else 0.0
        n_gws = int(_f(p["n_gws_available"])) if p is not None else 0
        total_points = _f(p["total_points"]) if p is not None else 0.0
        price = (_f(p["last_value"]) / 10.0) if p is not None else 0.0

        rows.append({
            "id": int(pid),
            "full_name": (r.get("full_name") if r is not None else str(pid)),
            "web_name": (r.get("web_name") if r is not None else str(pid)),
            "team_name": team_name,
            "team_short": (r.get("team_short") if r is not None else team_name[:3].upper()),
            # LIMITATION #3: promoted-club handling is not exercised here.
            "is_promoted": False,
            "position": position,
            "price_m": price,
            "total_points": total_points,
            "points_per_game": f"{(total_points / n_gws) if n_gws else 0.0:.1f}",
            "form": f"{(total_points / n_gws) if n_gws else 0.0:.1f}",
            "selected_by_percent": "0.0",
            "minutes": minutes,
            "starts": starts,
            "goals_scored": _f(p["goals_scored"]) if p is not None else 0.0,
            "assists": _f(p["assists"]) if p is not None else 0.0,
            "clean_sheets": _f(p["clean_sheets"]) if p is not None else 0.0,
            "goals_conceded": _f(p["goals_conceded"]) if p is not None else 0.0,
            "expected_goals": _f(p["expected_goals"]) if p is not None else 0.0,
            "expected_assists": _f(p["expected_assists"]) if p is not None else 0.0,
            "expected_goal_involvements": (
                (_f(p["expected_goals"]) + _f(p["expected_assists"]))
                if p is not None else 0.0),
            "expected_goals_conceded": (
                _f(p["expected_goals_conceded"]) if p is not None else 0.0),
            "bonus": _f(p["bonus"]) if p is not None else 0.0,
            "bps": _f(p["bps"]) if p is not None else 0.0,
            "ict_index": f"{_f(p['ict_index']) if p is not None else 0.0:.1f}",
            # LIMITATION #2: per-gameweek availability is not reconstructible,
            # so everyone is treated as fit. Documented in the report.
            "status": "a",
            "status_meaning": "available",
            "chance_of_playing_next_round": None,
            "news": "",
            # Backtest-only bookkeeping (ignored by the model).
            "n_appearances": (_f(p["n_appearances"]) if p is not None else 0.0),
            "n_gws_available": n_gws,
        })

    return pd.DataFrame(rows)


def build_fixtures_frame(hist: HistoricalData, target_gw: int) -> pd.DataFrame:
    """GW-N fixtures in load_fixtures_df() shape, with RESULTS STRIPPED.

    Only pre-match information survives: who plays whom, home/away, and FPL's
    published difficulty ratings (which are set in advance). `team_h_score`,
    `team_a_score` and `finished` are dropped here so no downstream code can
    accidentally consume a result.
    """
    fx = hist.fixtures[hist.fixtures["gameweek"] == int(target_gw)].copy()
    keep = ["id", "gameweek", "home_team", "home_short", "away_team",
            "away_short", "team_h_difficulty", "team_a_difficulty"]
    keep = [c for c in keep if c in fx.columns]
    fx = fx[keep].dropna(subset=["home_team", "away_team"])
    fx["kickoff_time"] = None
    fx["finished"] = False
    return fx.reset_index(drop=True)


def get_actual_points(gw_df: pd.DataFrame, target_gw: int) -> pd.DataFrame:
    """GROUND TRUTH for gameweek N. The only `gw == N` filter in the harness.

    Kept as its own function so the prediction path and the scoring path are
    visibly disjoint: nothing that calls this feeds anything back into
    `aggregate_prior_history()` or the frame builders.
    """
    actual = gw_df[gw_df["gw"] == int(target_gw)].copy()
    # A player with two rows in one gameweek played a double gameweek; the model
    # sums components across both fixtures, so sum the actuals to match.
    numeric = [c for c in _NUMERIC_GW_COLUMNS if c in actual.columns]
    grouped = actual.groupby("element")[numeric].sum()
    grouped["n_fixtures_actual"] = actual.groupby("element").size()
    if "position" in actual.columns:
        grouped["actual_position"] = actual.groupby("element")["position"].last()
    return grouped


def fpl_official_xp(gw_df: pd.DataFrame, target_gw: int) -> pd.Series:
    """FPL's own published expected points for gameweek N — a RIVAL PREDICTOR.

    This reads `gw == N` rows, which looks like the leakage firewall being
    breached, so read this carefully: the `xP` column is FPL's *pre-match*
    projection (their `ep_this` field), snapshotted by the archive next to the
    result. Using it as a competing prediction for GW N is exactly as legitimate
    as using our own model's GW-N output. What would be illegitimate — and is
    not done anywhere — is feeding it back into `aggregate_prior_history()` or
    any model input. It is `fpl_xp`-prefixed everywhere and never enters
    `_CUMULATIVE_COLUMNS`.

    Summed across fixtures for double gameweeks, matching how both our model's
    components and the actual points are aggregated.

    Returns an empty Series if this round is one of the archive's all-zero gaps
    (see `gameweeks_with_fpl_xp`), so it is dropped from the comparison rather
    than scored as a confident prediction of nil.
    """
    if "fpl_xp" not in gw_df.columns:
        return pd.Series(dtype=float, name="baseline_fpl_xp")
    if int(target_gw) not in set(gameweeks_with_fpl_xp(gw_df)):
        return pd.Series(dtype=float, name="baseline_fpl_xp")
    rows = gw_df[gw_df["gw"] == int(target_gw)]
    out = rows.groupby("element")["fpl_xp"].sum().astype(float)
    out.name = "baseline_fpl_xp"
    return out



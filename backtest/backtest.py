@dataclass
class HistoricalData:
    """One historical season, normalised into canonical column names."""
    gw: pd.DataFrame                 # per player per gameweek (ground truth + features)
    teams: pd.DataFrame              # id, name, short_name, strength_*
    fixtures: pd.DataFrame           # id, gameweek, home_team, away_team, difficulties
    players_raw: pd.DataFrame        # id, web_name, full_name, position, team_name
    source: str = "real"             # "real" | "synthetic"
    base_dir: str | None = None
    warnings: list[str] = field(default_factory=list)

    @property
    def gameweeks(self) -> list[int]:
        return sorted(int(g) for g in self.gw["gw"].dropna().unique())


def historical_data_available(base_dir: str = DEFAULT_DATA_DIR) -> bool:
    """True if the minimum set of vaastav CSVs is present at `base_dir`."""
    return all(os.path.isfile(os.path.join(base_dir, f)) for f in REQUIRED_FILES)


def load_historical_gw_data(base_dir: str = DEFAULT_DATA_DIR) -> HistoricalData:
    """Load + normalise one season of vaastav archive CSVs from `base_dir`.

    This is deliberately the ONLY function in the harness that reads files, and
    it does nothing except read and rename. Point it at a folder and inspect the
    result to sanity-check the real data without running the backtest:

        from backtest import load_historical_gw_data
        h = load_historical_gw_data("data/raw/historical_2025_26")
        print(h.warnings)
        print(h.gw[["element", "gw", "minutes", "total_points"]].head())

    Expected files (all in `base_dir`):
        merged_gw.csv    required — per-player per-gameweek actuals
        teams.csv        required — team strength ratings
        fixtures.csv     required — fixtures, FDR, results
        players_raw.csv  optional but recommended — roster identity/position

    Column-name variation across seasons is absorbed by `_GW_COLUMN_ALIASES`;
    anything genuinely missing is filled with a safe default AND recorded in
    `.warnings` so it is never a silent hole.

    Raises:
        FileNotFoundError if a required file is missing.
    """
    warnings: list[str] = []
    for fname in REQUIRED_FILES:
        path = os.path.join(base_dir, fname)
        if not os.path.isfile(path):
            raise FileNotFoundError(
                f"required file not found: {path}\n"
                f"Download it from https://raw.githubusercontent.com/vaastav/"
                f"Fantasy-Premier-League/master/data/2025-26/..."
            )

    teams = _normalise_teams(
        pd.read_csv(os.path.join(base_dir, "teams.csv")), warnings)
    fixtures = _normalise_fixtures(
        pd.read_csv(os.path.join(base_dir, "fixtures.csv")), teams, warnings)
    gw = _normalise_gw_table(
        pd.read_csv(os.path.join(base_dir, "merged_gw.csv"), low_memory=False),
        warnings)

    players_raw_path = os.path.join(base_dir, "players_raw.csv")
    cleaned_path = os.path.join(base_dir, "cleaned_players.csv")
    if os.path.isfile(players_raw_path):
        players_raw = _normalise_players_raw(
            pd.read_csv(players_raw_path), teams, warnings)
    elif os.path.isfile(cleaned_path):
        warnings.append(
            "players_raw.csv absent; falling back to cleaned_players.csv, which "
            "has no `id` column — player identity will come from merged_gw.csv.")
        players_raw = _players_raw_from_gw(gw, warnings)
    else:
        warnings.append(
            "no players_raw.csv/cleaned_players.csv; deriving roster from "
            "merged_gw.csv (fine, but GW1 predictions will have an empty pool "
            "unless merged_gw has GW1 rows).")
        players_raw = _players_raw_from_gw(gw, warnings)

    # Attach own-team names to the gameweek rows. Preferred source is the
    # merged_gw `team` column; where that is absent (older seasons) we recover it
    # from the fixture: own team = home team if was_home else away team. That is
    # a structural lookup, not an outcome, so it leaks nothing.
    gw = _attach_team_names(gw, fixtures, teams, players_raw, warnings)

    return HistoricalData(gw=gw, teams=teams, fixtures=fixtures,
                          players_raw=players_raw, source="real",
                          base_dir=base_dir, warnings=warnings)


def _normalise_gw_table(raw: pd.DataFrame, warnings: list[str]) -> pd.DataFrame:
    """merged_gw.csv -> canonical columns, correct dtypes."""
    out = pd.DataFrame(index=raw.index)

    for canonical, aliases in _GW_COLUMN_ALIASES.items():
        col = _find_column(raw, aliases)
        if col is None:
            continue
        out[canonical] = raw[col]

    if "element" not in out.columns:
        raise ValueError("merged_gw.csv has no `element` (player id) column")
    if "gw" not in out.columns:
        raise ValueError("merged_gw.csv has no gameweek column (GW/round/event)")

    out["element"] = pd.to_numeric(out["element"], errors="coerce").astype("Int64")
    out["gw"] = pd.to_numeric(out["gw"], errors="coerce").astype("Int64")
    out = out.dropna(subset=["element", "gw"]).copy()
    out["element"] = out["element"].astype(int)
    out["gw"] = out["gw"].astype(int)

    for col in _NUMERIC_GW_COLUMNS:
        if col in out.columns:
            out[col] = pd.to_numeric(out[col], errors="coerce").fillna(0.0).astype(float)
        else:
            out[col] = 0.0
            if col in ("minutes", "total_points", "goals_scored", "assists",
                       "clean_sheets", "bonus"):
                warnings.append(
                    f"merged_gw.csv is missing `{col}` — filled with 0.0. "
                    f"Metrics touching it will be wrong.")

    if "starts" not in raw.columns and "started" not in raw.columns:
        # Pre-2019 archives have no `starts`. Approximate: 60+ minutes ~ a start.
        out["starts"] = (out["minutes"] >= 60).astype(float)
        warnings.append(
            "merged_gw.csv has no `starts` column — approximated as "
            "(minutes >= 60). Start-probability diagnostics are approximate.")

    if "was_home" in out.columns:
        out["was_home"] = out["was_home"].map(_as_bool)
    else:
        out["was_home"] = False
        warnings.append("merged_gw.csv has no `was_home` column.")

    if "position" in out.columns:
        out["position"] = out["position"].map(normalise_position)
    else:
        warnings.append("merged_gw.csv has no `position` column.")

    if "fixture" in out.columns:
        out["fixture"] = pd.to_numeric(out["fixture"], errors="coerce").astype("Int64")
    if "opponent_team" in out.columns:
        out["opponent_team"] = pd.to_numeric(
            out["opponent_team"], errors="coerce").astype("Int64")

    if float(out["expected_goals"].abs().sum()) == 0.0:
        warnings.append(
            "merged_gw.csv `expected_goals` is all zero (pre-2022 seasons have "
            "no xG). The model will fall back almost entirely to XG90_PRIOR.")

    # FPL's own xP. Coerced here rather than via _NUMERIC_GW_COLUMNS so it stays
    # visibly separate from the ground-truth/feature columns.
    if "fpl_xp" in out.columns:
        out["fpl_xp"] = pd.to_numeric(out["fpl_xp"], errors="coerce")
        # DATA-QUALITY LANDMINE: in the 2025/26 dump this column is populated
        # for only a minority of gameweeks — for the rest the scraper wrote 0.0
        # for every single player. An all-zero round is missing data, not a
        # prediction of "nobody scores", and averaging it in would silently
        # hand our model a fake win. Detect and record which rounds are usable.
        usable = gameweeks_with_fpl_xp(out)
        all_gws = sorted(int(g) for g in out["gw"].unique())
        missing = [g for g in all_gws if g not in set(usable)]
        per_round = all_gws
        if missing:
            warnings.append(
                f"merged_gw.csv `xP` (FPL's own expected points) is all-zero for "
                f"{len(missing)} of {len(per_round)} gameweeks: {missing}. Those "
                f"rounds are treated as MISSING, not as a prediction of zero. The "
                f"FPL-xP baseline is therefore scored only on gameweeks {usable}, "
                f"and our model is re-scored on that same subset for a fair "
                f"head-to-head.")
    else:
        warnings.append(
            "merged_gw.csv has no `xP` column — the FPL-official-xP baseline "
            "is unavailable for this season.")

    return out.reset_index(drop=True)


def _normalise_teams(raw: pd.DataFrame, warnings: list[str]) -> pd.DataFrame:
    """teams.csv -> the exact shape fpl_client.load_teams_df() produces."""
    out = raw.copy()
    if "name" not in out.columns:
        raise ValueError("teams.csv has no `name` column")
    if "id" not in out.columns:
        raise ValueError("teams.csv has no `id` column")
    out["id"] = pd.to_numeric(out["id"], errors="coerce").astype(int)

    strength_cols = ["strength_overall_home", "strength_overall_away",
                     "strength_attack_home", "strength_attack_away",
                     "strength_defence_home", "strength_defence_away"]
    for col in strength_cols + ["strength"]:
        if col not in out.columns:
            out[col] = m.DEFAULT_TEAM_STRENGTH
            warnings.append(
                f"teams.csv missing `{col}` — defaulted to "
                f"DEFAULT_TEAM_STRENGTH ({m.DEFAULT_TEAM_STRENGTH}). The "
                f"fixture model is effectively disabled on that axis.")
        else:
            out[col] = pd.to_numeric(out[col], errors="coerce").fillna(
                m.DEFAULT_TEAM_STRENGTH).astype(float)

    if "short_name" not in out.columns:
        out["short_name"] = out["name"].astype(str).str[:3].str.upper()

    # No promoted-club handling in the backtest — see LIMITATIONS #3.
    out["is_promoted"] = False

    keep = ["id", "name", "short_name", "strength"] + strength_cols + ["is_promoted"]
    return out[keep].reset_index(drop=True)


def _normalise_fixtures(raw: pd.DataFrame, teams: pd.DataFrame,
                        warnings: list[str]) -> pd.DataFrame:
    """fixtures.csv -> id/gameweek/home_team/away_team/difficulties (+ results).

    Results (`team_h_score`, `team_a_score`, `finished`) are carried on the frame
    for reporting only. `build_fixtures_frame()` strips them before anything is
    handed to the model.
    """
    out = raw.copy()
    name_by_id = dict(zip(teams["id"], teams["name"]))
    short_by_id = dict(zip(teams["id"], teams["short_name"]))

    gw_col = _find_column(out, ("event", "GW", "round", "gameweek"))
    if gw_col is None:
        raise ValueError("fixtures.csv has no gameweek column (`event`)")
    out["gameweek"] = pd.to_numeric(out[gw_col], errors="coerce")

    for side, col in (("home", "team_h"), ("away", "team_a")):
        if col not in out.columns:
            raise ValueError(f"fixtures.csv has no `{col}` column")
        out[col] = pd.to_numeric(out[col], errors="coerce").astype("Int64")
        out[f"{side}_team"] = out[col].map(name_by_id)
        out[f"{side}_short"] = out[col].map(short_by_id)

    for col in ("team_h_difficulty", "team_a_difficulty"):
        if col not in out.columns:
            out[col] = 3
            warnings.append(
                f"fixtures.csv missing `{col}` — defaulted to 3 (neutral). "
                f"DIFFICULTY_* multipliers become no-ops.")
        else:
            out[col] = pd.to_numeric(out[col], errors="coerce").fillna(3).astype(int)

    for col in ("team_h_score", "team_a_score"):
        if col not in out.columns:
            out[col] = np.nan
        else:
            out[col] = pd.to_numeric(out[col], errors="coerce")

    if "id" not in out.columns:
        out["id"] = range(1, len(out) + 1)
    out["id"] = pd.to_numeric(out["id"], errors="coerce").astype("Int64")

    unmapped = out["home_team"].isna().sum() + out["away_team"].isna().sum()
    if unmapped:
        warnings.append(
            f"{unmapped} fixture team ids did not map to teams.csv names — "
            f"those fixtures will look like blank gameweeks to the model.")

    out = out.dropna(subset=["gameweek"]).copy()
    out["gameweek"] = out["gameweek"].astype(int)
    keep = ["id", "gameweek", "team_h", "team_a", "home_team", "home_short",
            "away_team", "away_short", "team_h_difficulty", "team_a_difficulty",
            "team_h_score", "team_a_score"]
    keep = [c for c in keep if c in out.columns]
    return out[keep].reset_index(drop=True)


def _normalise_players_raw(raw: pd.DataFrame, teams: pd.DataFrame,
                           warnings: list[str]) -> pd.DataFrame:
    """players_raw.csv -> IDENTITY ONLY (id, names, position, team).

    Deliberately drops every statistic. players_raw.csv is an END-OF-SEASON
    snapshot: its `total_points`, `minutes`, `now_cost` etc. describe the whole
    season and using any of them as a gameweek-N feature would be textbook
    lookahead.
    """
    out = raw.copy()
    if "id" not in out.columns:
        raise ValueError("players_raw.csv has no `id` column")
    out["id"] = pd.to_numeric(out["id"], errors="coerce").astype("Int64")

    pos_col = _find_column(out, ("element_type", "position"))
    out["position"] = out[pos_col].map(normalise_position) if pos_col else "MID"
    if pos_col is None:
        warnings.append("players_raw.csv has no element_type/position column.")

    name_by_id = dict(zip(teams["id"], teams["name"]))
    short_by_id = dict(zip(teams["id"], teams["short_name"]))
    if "team" in out.columns:
        team_ids = pd.to_numeric(out["team"], errors="coerce")
        out["team_name"] = team_ids.map(name_by_id)
        out["team_short"] = team_ids.map(short_by_id)
    else:
        out["team_name"] = None
        out["team_short"] = None
        warnings.append("players_raw.csv has no `team` column.")

    if "web_name" not in out.columns:
        out["web_name"] = out.get("second_name", out.get("first_name", "?"))
    first = out["first_name"] if "first_name" in out.columns else ""
    second = out["second_name"] if "second_name" in out.columns else out["web_name"]
    out["full_name"] = (pd.Series(first, index=out.index).fillna("").astype(str)
                        + " "
                        + pd.Series(second, index=out.index).fillna("").astype(str)
                        ).str.strip()

    return out[["id", "web_name", "full_name", "position", "team_name",
                "team_short"]].dropna(subset=["id"]).reset_index(drop=True)


def _players_raw_from_gw(gw: pd.DataFrame, warnings: list[str]) -> pd.DataFrame:
    """Reconstruct a roster from merged_gw when players_raw.csv is unavailable."""
    cols = {"id": gw["element"]}
    frame = pd.DataFrame(cols)
    frame["web_name"] = gw["name"] if "name" in gw.columns else gw["element"].astype(str)
    frame["full_name"] = frame["web_name"]
    frame["position"] = gw["position"] if "position" in gw.columns else "MID"
    frame["team_name"] = gw["team"] if "team" in gw.columns else None
    frame["team_short"] = None
    # Keep the LAST row per player so a mid-season transfer resolves to the
    # club they ended at; per-gameweek club is re-derived from history anyway.
    return frame.drop_duplicates(subset=["id"], keep="last").reset_index(drop=True)


def _attach_team_names(gw: pd.DataFrame, fixtures: pd.DataFrame,
                       teams: pd.DataFrame, players_raw: pd.DataFrame,
                       warnings: list[str]) -> pd.DataFrame:
    """Ensure every gameweek row carries a `team` name matching teams.csv."""
    out = gw.copy()
    valid_names = set(teams["name"].astype(str))

    have_team = "team" in out.columns and out["team"].notna().any()
    if have_team:
        matched = out["team"].astype(str).isin(valid_names).mean()
        if matched > 0.95:
            out["team"] = out["team"].astype(str)
            return out
        warnings.append(
            f"merged_gw.csv `team` values match teams.csv names only "
            f"{matched:.0%} of the time — rebuilding own-team from fixtures.")

    if "fixture" in out.columns and "was_home" in out.columns:
        fx = fixtures.set_index("id")[["home_team", "away_team"]]
        home = out["fixture"].map(fx["home_team"])
        away = out["fixture"].map(fx["away_team"])
        out["team"] = np.where(out["was_home"].astype(bool), home, away)
        missing = pd.isna(out["team"]).mean()
        if missing > 0.01:
            warnings.append(
                f"{missing:.1%} of gameweek rows could not be matched to a "
                f"fixture — those players look club-less and will be dropped.")
        return out

    warnings.append(
        "cannot determine each player's club per gameweek (no `team` column and "
        "no fixture/was_home pair) — falling back to the end-of-season roster.")
    out["team"] = out["element"].map(dict(zip(players_raw["id"], players_raw["team_name"])))
    return out



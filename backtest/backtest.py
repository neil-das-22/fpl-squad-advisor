def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Backtest models/xp_model.py against a completed season.")
    parser.add_argument("--data-dir", default=DEFAULT_DATA_DIR,
                        help="folder holding merged_gw.csv, teams.csv, "
                             "fixtures.csv, players_raw.csv")
    parser.add_argument("--from-gw", type=int, default=1)
    parser.add_argument("--to-gw", type=int, default=None)
    parser.add_argument("--synthetic", action="store_true",
                        help="force synthetic self-test mode even if real data exists")
    parser.add_argument("--report", default=None, help="override report path")
    parser.add_argument("--quiet", action="store_true",
                        help="suppress the per-gameweek progress lines")
    args = parser.parse_args(argv)

    use_real = (not args.synthetic) and historical_data_available(args.data_dir)

    if use_real:
        print(f"[data] real historical CSVs found at {args.data_dir}")
        hist = load_historical_gw_data(args.data_dir)
        report_path = args.report or REAL_REPORT_PATH
    else:
        if args.synthetic:
            print("[data] --synthetic requested: running in SYNTHETIC SELF-TEST MODE")
        else:
            missing = [f for f in REQUIRED_FILES
                       if not os.path.isfile(os.path.join(args.data_dir, f))]
            print("=" * 74)
            print("  NO REAL HISTORICAL DATA FOUND — RUNNING IN SYNTHETIC SELF-TEST MODE")
            print("=" * 74)
            print(f"  Looked in : {args.data_dir}")
            print(f"  Missing   : {', '.join(missing)}")
            print("  Every number produced by this run is SIMULATED and tells you")
            print("  nothing about the real model's accuracy. Drop the four vaastav")
            print("  CSVs into the folder above and re-run for real findings.")
            print("=" * 74)
        hist = load_synthetic_dataset()
        report_path = args.report or SYNTHETIC_REPORT_PATH

    print(f"[data] {len(hist.gw):,} player-gameweek rows | "
          f"{len(hist.teams)} teams | {len(hist.fixtures)} fixtures | "
          f"gameweeks {min(hist.gameweeks)}-{max(hist.gameweeks)}")
    for w in hist.warnings:
        print(f"[warn] {w}")

    print("\n[run] replaying gameweeks (no lookahead: GW N sees only GW < N)")
    results = run_backtest(hist, from_gw=args.from_gw, to_gw=args.to_gw,
                           verbose=not args.quiet)

    report = build_report(results, hist, from_gw=args.from_gw,
                          to_gw=int(results["gameweek"].max()))
    os.makedirs(os.path.dirname(report_path), exist_ok=True)
    with open(report_path, "w") as fh:
        fh.write(report)

    print_console_summary(results, hist, report_path)
    return 0



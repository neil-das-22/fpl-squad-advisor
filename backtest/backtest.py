def build_baselines(prior: pd.DataFrame, players_df: pd.DataFrame,
                    gw_df: pd.DataFrame, target_gw: int) -> pd.DataFrame:
    """Naive predictors to beat, all built from pre-gameweek-N data only.

    * `baseline_zero`       — always predict 0. Sounds silly; is genuinely hard
      to beat on MAE because most rows in a gameweek are players who did not
      play. Included precisely to show why MAE alone is a bad yardstick.
    * `baseline_ppg`        — the player's season-to-date points per elapsed
      gameweek. The obvious "just look at the table" heuristic.
    * `baseline_position`   — the mean actual points scored by that position in
      gameweeks 1..N-1. A pure prior with no player information at all.
    """
    history = gw_df[gw_df["gw"] < int(target_gw)]           # firewall again
    out = pd.DataFrame(index=players_df["id"].values)
    out.index.name = "id"

    out["baseline_zero"] = 0.0

    ppg = {}
    for pid in out.index:
        if pid in prior.index:
            n = max(1.0, _f(prior.loc[pid, "n_gws_available"]))
            ppg[pid] = _f(prior.loc[pid, "total_points"]) / n
        else:
            ppg[pid] = 0.0
    out["baseline_ppg"] = pd.Series(ppg)

    if len(history) and "position" in history.columns:
        pos_mean = history.groupby(
            history["position"].map(normalise_position))["total_points"].mean()
    else:
        pos_mean = pd.Series(dtype=float)
    pos_by_id = dict(zip(players_df["id"], players_df["position"]))
    out["baseline_position"] = [
        float(pos_mean.get(pos_by_id.get(pid, "MID"), 0.0)) for pid in out.index
    ]
    return out


# ---------------------------------------------------------------------------
# 3b. DEFCON DATA-GAP EXPERIMENT
#
# xp_model KNOWN DATA GAP #2: fpl_client does not fetch the CBIT/CBIRT counting
# stats, so `calculate_xp()` falls back to a flat positional constant,
# DEFCON_PER90_PRIOR = {DEF: 6.5, MID: 8.5, FWD: 5.0}. Every defender in the
# league is therefore assumed to make clearances at an identical rate — which is
# obviously false (a centre-back heading everything vs an inverted full-back).
#
# The 2025/26 archive DOES carry the real counting stats, so we can measure
# exactly what that gap costs: rebuild each player's own rolling CBIT/CBIRT rate
# from gameweeks 1..N-1 and re-score only the DefCon component.
# ---------------------------------------------------------------------------

def rolling_defcon_rates(prior: pd.DataFrame, players_df: pd.DataFrame
                         ) -> pd.DataFrame:
    """Each player's own CBIT/CBIRT per-90, from prior gameweeks only.

    `prior` is the output of `aggregate_prior_history()`, i.e. already firewalled
    to gameweeks < N. Nothing else is read, so this inherits the no-lookahead
    guarantee rather than needing its own.

    Note on which stat: FPL's DefCon threshold counts CBIT for defenders
    (clearances + blocks + interceptions + tackles) and CBIRT for mids/forwards
    (the same plus recoveries). The archive's `defensive_contribution` column is
    already the position-correct one — verified against the raw components:
    for DEF it equals cbi + tackles, for MID/FWD cbi + tackles + recoveries, in
    100% of rows. So we cumulate that column directly rather than re-deriving it
    and risking getting the position rule backwards.

    Returns columns:
        defcon_per90_raw    -- unshrunk total/90s. Noisy on small samples.
        defcon_per90_shrunk -- shrunk toward DEFCON_PER90_PRIOR with
                               DEFCON_ROLLING_PRIOR_WEIGHT_90S. This is the
                               headline "what a real pipeline would supply".
        defcon_prior_minutes-- minutes the rate is based on (for filtering).
    """
    idx = pd.Index(players_df["id"].values, name="id")
    pos_by_id = dict(zip(players_df["id"], players_df["position"]))
    out = pd.DataFrame(index=idx)

    if len(prior) == 0 or "defensive_contribution" not in prior.columns:
        out["defcon_per90_raw"] = np.nan
        out["defcon_per90_shrunk"] = np.nan
        out["defcon_prior_minutes"] = 0.0
        return out

    raw, shrunk, mins_col = [], [], []
    for pid in idx:
        pos = pos_by_id.get(pid, "MID")
        prior_rate = m.DEFCON_PER90_PRIOR.get(pos, 0.0)
        if pid not in prior.index:
            raw.append(np.nan)
            shrunk.append(np.nan)
            mins_col.append(0.0)
            continue
        total = _f(prior.loc[pid, "defensive_contribution"])
        minutes = _f(prior.loc[pid, "minutes"])
        mins_col.append(minutes)
        if minutes <= 0:
            raw.append(np.nan)
            shrunk.append(np.nan)
            continue
        raw.append(total / (minutes / 90.0))
        # Same empirical-Bayes helper the model already uses for xG/xA, so this
        # experiment isolates the value of the DATA, not of a new method.
        shrunk.append(m.shrunk_per90_rate(
            total, minutes, prior_rate,
            prior_weight_90s=DEFCON_ROLLING_PRIOR_WEIGHT_90S))

    out["defcon_per90_raw"] = raw
    out["defcon_per90_shrunk"] = shrunk
    out["defcon_prior_minutes"] = mins_col
    return out


def _defcon_points_from_rate(rate: float, position: str, p_60: float,
                             n_fixtures: float) -> float:
    """Re-implementation of xp_model's DefCon term for a supplied per-90 rate.

    Mirrors `calculate_xp()` exactly:
        mean_if_playing = rate * MEAN_MINUTES_IF_START / 90
        P(threshold)    = NB tail with DEFCON_OVERDISPERSION
        xp              = DEFCON_POINTS * P * p_60          (per fixture)

    `test_backtest.py::test_defcon_reimplementation_matches_model` asserts that
    feeding this the flat DEFCON_PER90_PRIOR reproduces the model's own
    `xp_defcon` column to within 1e-9, which is what licenses using it to score
    the alternative rate without re-running the whole model.
    """
    threshold = m.DEFCON_THRESHOLD.get(position)
    if threshold is None or not np.isfinite(rate) or rate <= 0:
        return 0.0
    mean_if_playing = rate * (m.MEAN_MINUTES_IF_START / 90.0)
    p = m.prob_at_least(threshold, mean_if_playing, m.DEFCON_OVERDISPERSION)
    return float(m.DEFCON_POINTS) * p * float(p_60) * float(n_fixtures)


def defcon_experiment(results: pd.DataFrame) -> dict[str, Any]:
    """Quantify what the missing CBIT/CBIRT feed costs the DefCon component.

    Compares three predictors of a player's actual DefCon points (0 or 2) in
    gameweek N:
        flat    -- DEFCON_PER90_PRIOR, i.e. what the live model does today.
        shrunk  -- the player's own rolling rate, shrunk to the positional prior.
        raw     -- the player's own rolling rate, unshrunk (shown to demonstrate
                   the shrinkage is doing real work, not just decoration).

    Restricted to outfield players with a DefCon threshold and enough prior
    minutes for a rolling rate to mean anything; goalkeepers have no threshold.

    Returns a dict of per-variant metrics plus a `table` DataFrame for the
    report and `n` / `n_gameweeks` for provenance.
    """
    df = results.copy()
    df["position"] = df["position"].map(normalise_position)

    eligible = (
        df["position"].isin(["DEF", "MID", "FWD"])
        & (~df.get("blank", pd.Series(False, index=df.index)).astype(bool))
        & (df["defcon_prior_minutes"].fillna(0.0) >= DEFCON_MIN_PRIOR_MINUTES)
        & df["defcon_per90_shrunk"].notna()
    )
    df = df[eligible].copy()
    if len(df) == 0:
        return {"n": 0, "table": pd.DataFrame(), "n_gameweeks": 0}

    # Actual DefCon points: +2 for hitting the position's threshold, else 0.
    thresholds = df["position"].map(m.DEFCON_THRESHOLD).astype(float)
    df["defcon_actual"] = np.where(
        df["defensive_contribution"].astype(float) >= thresholds,
        float(m.DEFCON_POINTS), 0.0)

    # p_60 is not returned by calculate_xp_for_gameweek, but every backtested
    # player has status 'a' (availability = 1.0), so minutes_distribution gives
    # exactly p_60 = p_start * P_60_GIVEN_START. The reimplementation test pins
    # this down rather than trusting the algebra.
    p_60 = df["p_start"].astype(float) * m.P_60_GIVEN_START
    n_fix = df["n_fixtures"].astype(float).clip(lower=0)

    df["defcon_pred_flat"] = [
        _defcon_points_from_rate(m.DEFCON_PER90_PRIOR.get(pos, 0.0), pos, p, k)
        for pos, p, k in zip(df["position"], p_60, n_fix)
    ]
    for variant, col in (("shrunk", "defcon_per90_shrunk"),
                         ("raw", "defcon_per90_raw")):
        df[f"defcon_pred_{variant}"] = [
            _defcon_points_from_rate(r, pos, p, k)
            for r, pos, p, k in zip(df[col], df["position"], p_60, n_fix)
        ]

    rows = []
    for label, col in (("flat prior (live model today)", "defcon_pred_flat"),
                       ("own rolling rate, shrunk", "defcon_pred_shrunk"),
                       ("own rolling rate, raw", "defcon_pred_raw")):
        pred, act = df[col], df["defcon_actual"]
        # Actual is binary 0/2, so MAE on points is a Brier-like proper-ish
        # score; rank correlation says whether it sorts players correctly.
        rows.append({
            "variant": label,
            "n": int(len(df)),
            "mae": mae(pred, act),
            "rmse": rmse(pred, act),
            "bias": bias(pred, act),
            "spearman": spearman(pred, act),
            "mean_pred": float(pred.mean()),
            "mean_actual": float(act.mean()),
            # Of the 50 players this variant most expects to hit the threshold
            # each gameweek, what fraction actually did.
            "top50_hit_rate": _defcon_top_n_hit_rate(df, col, 50),
        })

    table = pd.DataFrame(rows)
    flat_mae = table.loc[0, "mae"]
    shrunk_mae = table.loc[1, "mae"]
    return {
        "n": int(len(df)),
        "n_gameweeks": int(df["gameweek"].nunique()),
        "table": table,
        "mae_flat": float(flat_mae),
        "mae_shrunk": float(shrunk_mae),
        "mae_improvement": float(flat_mae - shrunk_mae),
        "mae_improvement_pct": float((flat_mae - shrunk_mae) / flat_mae * 100.0)
        if flat_mae else float("nan"),
        "spearman_flat": float(table.loc[0, "spearman"]),
        "spearman_shrunk": float(table.loc[1, "spearman"]),
        "base_rate": float(df["defcon_actual"].mean() / m.DEFCON_POINTS),
        "rate_spread": {
            "flat_unique_values": int(pd.Series(
                [m.DEFCON_PER90_PRIOR.get(p, 0.0) for p in df["position"]]).nunique()),
            "rolling_p10": float(df["defcon_per90_shrunk"].quantile(0.10)),
            "rolling_median": float(df["defcon_per90_shrunk"].median()),
            "rolling_p90": float(df["defcon_per90_shrunk"].quantile(0.90)),
        },
    }


def _defcon_top_n_hit_rate(df: pd.DataFrame, pred_col: str, n: int) -> float:
    """Per gameweek, take the n highest DefCon predictions; what fraction hit?"""
    hits, picks = 0, 0
    for _, grp in df.groupby("gameweek"):
        top = grp.nlargest(min(n, len(grp)), pred_col)
        hits += int((top["defcon_actual"] > 0).sum())
        picks += len(top)
    return hits / picks if picks else float("nan")


# ---------------------------------------------------------------------------
# 4. RUNNING ONE GAMEWEEK / THE WHOLE SEASON
# ---------------------------------------------------------------------------

def run_gameweek(hist: HistoricalData, target_gw: int,
                 verbose: bool = False) -> pd.DataFrame:
    """Predict GW N from pre-N data, then join on the real GW N outcome.

    Returns one row per player with `predicted`, `actual`, every xP component,
    and the baselines. Empty frame if the gameweek has no fixtures or no data.
    """
    prior = aggregate_prior_history(hist.gw, target_gw)
    players_df = build_players_frame(hist, prior, target_gw)
    fixtures_df = build_fixtures_frame(hist, target_gw)

    if len(players_df) == 0 or len(fixtures_df) == 0:
        if verbose:
            print(f"  GW{target_gw}: skipped "
                  f"({len(players_df)} players, {len(fixtures_df)} fixtures)")
        return pd.DataFrame()

    pred = m.calculate_xp_for_gameweek(
        players_df, hist.teams, fixtures_df, gameweek=int(target_gw))

    actual = get_actual_points(hist.gw, target_gw)
    if len(actual) == 0:
        return pd.DataFrame()

    baselines = build_baselines(prior, players_df, hist.gw, target_gw)

    merged = pred.merge(actual, left_on="id", right_index=True, how="inner")
    merged = merged.merge(baselines, left_on="id", right_index=True, how="left")
    merged = merged.merge(
        players_df[["id", "n_appearances", "n_gws_available"]], on="id", how="left")

    # Fourth baseline: FPL's own published xP. NaN (not 0) on rounds the archive
    # failed to capture, so those rows drop out of the comparison cleanly.
    fpl = fpl_official_xp(hist.gw, target_gw)
    merged = merged.merge(fpl, left_on="id", right_index=True, how="left")
    if "baseline_fpl_xp" not in merged.columns:
        merged["baseline_fpl_xp"] = np.nan

    # DEFCON DATA-GAP EXPERIMENT inputs. Built from `prior` (gameweeks < N) only,
    # so they are as lookahead-free as every other feature here.
    merged = merged.merge(rolling_defcon_rates(prior, players_df),
                          left_on="id", right_index=True, how="left")

    merged["gameweek"] = int(target_gw)
    merged["predicted"] = merged["xp"].astype(float)
    merged["actual"] = merged["total_points"].astype(float)
    merged["is_cold_start"] = int(target_gw) <= COLD_START_MAX_GW
    merged["blank"] = merged["n_fixtures"] == 0

    if verbose:
        print(f"  GW{target_gw}: {len(merged):4d} players | "
              f"mean pred {merged['predicted'].mean():.2f} | "
              f"mean actual {merged['actual'].mean():.2f}")
    return merged


def run_backtest(hist: HistoricalData, from_gw: int = 1,
                 to_gw: int | None = None, verbose: bool = True) -> pd.DataFrame:
    """Replay every gameweek in [from_gw, to_gw] and stack the results."""
    available = hist.gameweeks
    if not available:
        raise ValueError("no gameweeks found in the historical data")
    to_gw = to_gw if to_gw is not None else max(available)

    frames = []
    for gw in range(int(from_gw), int(to_gw) + 1):
        if gw not in available:
            continue
        frames.append(run_gameweek(hist, gw, verbose=verbose))

    frames = [f for f in frames if len(f)]
    if not frames:
        raise ValueError("backtest produced no rows — check the input data")
    return pd.concat(frames, ignore_index=True)



def _md_table(df: pd.DataFrame, floatfmt: int = 3) -> str:
    if df is None or len(df) == 0:
        return "_(no data)_\n"
    cols = list(df.columns)
    lines = ["| " + " | ".join(str(c) for c in cols) + " |",
             "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, row in df.iterrows():
        cells = []
        for c in cols:
            v = row[c]
            if isinstance(v, (int, np.integer)):
                cells.append(str(int(v)))
            elif isinstance(v, (float, np.floating)):
                cells.append("n/a" if not np.isfinite(v) else f"{v:.{floatfmt}f}")
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def credible_pool(results: pd.DataFrame) -> pd.DataFrame:
    """Players with at least one appearance before the gameweek being predicted.

    Conditions ONLY on pre-gameweek information (`n_appearances` is built inside
    the leakage firewall), so this is a legitimate evaluation slice, not
    outcome-peeking. It exists because the raw pool is ~40% players who never
    play at all, and their error is so large and so one-directional that it
    masks every genuine calibration signal in the model.
    """
    if "n_appearances" not in results.columns:
        return results
    return results[results["n_appearances"].fillna(0) >= 1]


def _slice_metrics_table(slices: dict[str, pd.DataFrame]) -> pd.DataFrame:
    rows = []
    for label, sl in slices.items():
        block = metric_block(sl)
        if block.get("n", 0) == 0:
            continue
        rows.append({"slice": label, **block})
    return pd.DataFrame(rows)



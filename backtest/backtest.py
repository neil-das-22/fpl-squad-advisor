        W("recorded **zero minutes in every completed gameweek so far** — squad")
        W("filler, academy names, permanently-benched keepers.")
        W("")
        W(f"- The model gave them a mean start probability of "
          f"**{ghost['mean_p_start']:.3f}** and predicted "
          f"**{ghost['mean_pred']:.2f} xP** each.")
        W(f"- They actually scored **{ghost['mean_actual']:.3f}** points on average, "
          f"and featured at all in **{ghost['pct_who_played']:.1%}** of cases.")
